// SQL used by supabase-admin.mjs (kept separate so it can be tested against a local Postgres).

// Every ordinary table in the public schema (so nothing is missed, whatever the project contains).
export const tablesSql = `select c.relname as name from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind in ('r','p') order by 1`;
export const rowsSql = (t) => `select coalesce(jsonb_agg(to_jsonb(t) order by to_jsonb(t)::text), '[]'::jsonb) as rows from public."${t}" t`;
export const countSql = (t) => `select count(*)::int as n from public."${t}"`;
// A fingerprint of a table's contents that doesn't depend on row order.
export const md5Sql = (t) => `select md5(coalesce(string_agg(to_jsonb(t)::text, '|' order by to_jsonb(t)::text), '')) as md5 from public."${t}" t`;

// The complete structure of the public schema as an ordered list of SQL statements (sec = order of execution).
// Covers tables, sequences, constraints, indexes, row-level security, policies, functions, views, triggers and grants.
export const ddlSql = `
with t as (select c.oid, c.relname from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind in ('r','p')),
ext as (select objid from pg_depend where deptype='e'),
stmts(sec, stmt) as (
  -- sequences referenced by column defaults
  select 10, format('create sequence if not exists %s;', case when s like '%.%' then s else 'public.'||s end)
    from (select distinct (regexp_match(pg_get_expr(d.adbin,d.adrelid), 'nextval\\(''([^'']+)''::regclass\\)'))[1] s from pg_attrdef d join t on t.oid=d.adrelid) q where s is not null
  union all
  select 20, format('create table public.%I (%s);', t.relname, string_agg(
      format('%I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
        case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end,
        case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
             when a.attidentity = '' and d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
        case when a.attnotnull then ' not null' else '' end), ', ' order by a.attnum))
    from t join pg_attribute a on a.attrelid=t.oid and a.attnum>0 and not a.attisdropped
    left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum group by t.relname
  union all
  select 50, format('alter table public.%I add constraint %I %s;', cl.relname, co.conname, pg_get_constraintdef(co.oid))
    from pg_constraint co join pg_class cl on cl.oid=co.conrelid join t on t.oid=cl.oid where co.contype in ('p','u','c')
  union all
  select 60, format('alter table public.%I add constraint %I %s;', cl.relname, co.conname, pg_get_constraintdef(co.oid))
    from pg_constraint co join pg_class cl on cl.oid=co.conrelid join t on t.oid=cl.oid where co.contype in ('f','x')
  union all
  select 70, i.indexdef || ';' from pg_indexes i where i.schemaname='public'
    and not exists (select 1 from pg_constraint co join pg_class cl on cl.oid=co.conrelid where co.conname=i.indexname and cl.relname=i.tablename)
  union all
  select 80, format('alter table public.%I enable row level security;', t.relname) from t join pg_class c on c.oid=t.oid where c.relrowsecurity
  union all
  select 81, format('alter table public.%I force row level security;', t.relname) from t join pg_class c on c.oid=t.oid where c.relforcerowsecurity
  union all
  select 82, format('create policy %I on public.%I as %s for %s to %s%s%s;', policyname, tablename, lower(permissive), cmd, array_to_string(roles, ', '),
      case when qual is not null then ' using (' || qual || ')' else '' end, case when with_check is not null then ' with check (' || with_check || ')' else '' end)
    from pg_policies where schemaname='public'
  union all
  select 40, pg_get_functiondef(p.oid) || ';' from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.prokind in ('f','p') and p.oid not in (select objid from ext)
  union all
  select 91, format('create or replace view public.%I as %s', viewname, definition) from pg_views where schemaname='public'
  union all
  select 92, pg_get_triggerdef(tg.oid) || ';' from pg_trigger tg join t on t.oid=tg.tgrelid where not tg.tgisinternal
  union all
  select 100, format('grant %s on %s public.%I to %s;', string_agg(privilege_type, ', ' order by privilege_type), kind, relname, grantee)
    from (select c.relname, case when c.relkind='S' then 'sequence' else 'table' end kind, x.privilege_type, r.rolname grantee
          from pg_class c join pg_namespace n on n.oid=c.relnamespace, lateral aclexplode(c.relacl) x join pg_roles r on r.oid=x.grantee
          where n.nspname='public' and c.relkind in ('r','p','v','m','S') and r.rolname in ('anon','authenticated','service_role')) g group by relname, kind, grantee
  union all
  select 101, format('grant execute on function %s to %s;', p.oid::regprocedure, r.rolname)
    from pg_proc p join pg_namespace n on n.oid=p.pronamespace, lateral aclexplode(p.proacl) x join pg_roles r on r.oid=x.grantee
    where n.nspname='public' and p.prokind in ('f','p') and r.rolname in ('anon','authenticated','service_role') and p.oid not in (select objid from ext)
  union all
  -- after loading rows: continue every id counter from the highest id
  select 110, format('select setval(pg_get_serial_sequence(''public.%I'', %L), greatest(coalesce((select max(%I) from public.%I), 0), 1), exists (select 1 from public.%I));', t.relname, a.attname, a.attname, t.relname, t.relname)
    from t join pg_attribute a on a.attrelid=t.oid and a.attnum>0 and not a.attisdropped
    left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum
    where a.attidentity <> '' or pg_get_expr(d.adbin, d.adrelid) like 'nextval(%'
)
select sec, stmt from stmts order by sec, stmt`;

// Applies a migration (or several) inside a transaction that is ALWAYS rolled back (the DO block raises on purpose).
export const preflightSql = (migration) => `begin;
${migration}
do $pf$ declare n_tables int; n_pol int; n_fn int; n_anon int; begin
  select count(*) into n_tables from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and relkind='r' and relrowsecurity;
  select count(*) into n_pol from pg_policies where schemaname='public' and policyname='owner_all';
  select count(*) into n_fn from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and proname like 'fos_%';
  select count(*) into n_anon from information_schema.role_table_grants where table_schema='public' and grantee='anon';
  raise exception 'PREFLIGHT_OK rls_tables=% owner_policies=% fos_functions=% anon_table_grants=%', n_tables, n_pol, n_fn, n_anon;
end $pf$;`;
